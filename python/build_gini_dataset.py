def build_acs_panel(state: str) -> dict:
    """
    Build year → Gini dict for 2006–2024 using two anchor points.
    - 2006–2019: linear interpolation from Frank-2005 endpoint to ACS-2019
    - 2020:      imputed as mean(2019, 2021)
    - 2021–2024: linear interpolation from ACS-2019 toward ACS-2024
    """
    g05 = HISTORICAL_GINI[state][2005]
    g19 = ACS_2019[state]
    g24 = ACS_2024[state]

    result = {}
    # 2006–2019: interpolate Frank endpoint → ACS 2019
    for year in range(2006, 2020):
        t = (year - 2005) / (2019 - 2005)
        result[year] = round(g05 + t * (g19 - g05), 4)
    result[2019] = round(g19, 4)

    # 2021–2024: interpolate ACS 2019 → ACS 2024
    for year in range(2021, 2025):
        t = (year - 2019) / (2024 - 2019)
        result[year] = round(g19 + t * (g24 - g19), 4)

    # 2020: impute as average of 2019 and 2021
    result[2020] = round((result[2019] + result[2021]) / 2, 4)

    return result


