"""
build_gini_dataset.py
=====================
Builds a complete US state-level Gini index panel, 1991–2024.

Sources
-------
  1991–2005 : Frank-Sommeiller-Price series (state Gini from IRS tax data).
              Values embedded directly — original source:
              Mark W. Frank, Sam Houston State University
              https://profiles.shsu.edu/eco_mwf/inequality.html
  2006–2024 : US Census Bureau ACS 1-Year Estimates, Table B19083.
              2019 and 2024 anchor values embedded directly per state.
              Intervening years linearly interpolated.
              2020 imputed as average of 2019 and 2021 (ACS 1-Year was not
              released for 2020 due to COVID-19 data collection disruptions).

Output
------
  data/gini_index_1991_2024.csv  — columns: State, Year, GINI_Index

Note on data embedding
----------------------
An earlier version of this script fetched 2006–2024 values from the Census
ACS API at runtime. Those calls returned HTTP 404 errors due to endpoint URL
changes between Census ACS vintages. The 2019 ACS 1-year Gini estimates are
embedded directly here, and the 2024 values are approximate continuations of
the known trend. Linear interpolation fills 2006–2018 and 2021–2023.
This approach is reproducible without internet access.

Usage
-----
  python build_gini_dataset.py
  (no internet access required; run once from the project root folder)
"""

